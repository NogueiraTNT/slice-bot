"""Deploy Sally brain to VPS in a NEW path — does not touch existing services.

Env: SALLY_VPS_HOST, SALLY_VPS_USER, SALLY_VPS_PASS
"""

from __future__ import annotations

import io
import os
import posixpath
import sys
import tarfile
import time
from pathlib import Path

import paramiko

ROOT = Path(__file__).resolve().parents[1]
REMOTE_ROOT = "/opt/sally-cibote"
REMOTE_PORT = 8765
# Docker Ollama with qwen2.5:3b (NOT host :11434 llama3.2:1b)
OLLAMA_URL = "http://127.0.0.1:32768"
MODEL = "qwen2.5:3b"


def connect() -> paramiko.SSHClient:
    client = paramiko.SSHClient()
    client.set_missing_host_key_policy(paramiko.AutoAddPolicy())
    client.connect(
        hostname=os.environ["SALLY_VPS_HOST"].strip(),
        username=os.environ.get("SALLY_VPS_USER", "root").strip(),
        password=os.environ["SALLY_VPS_PASS"],
        timeout=30,
        allow_agent=False,
        look_for_keys=False,
    )
    return client


def run(client: paramiko.SSHClient, cmd: str, timeout: int = 300) -> tuple[int, str, str]:
    _, stdout, stderr = client.exec_command(cmd, timeout=timeout)
    out = stdout.read().decode("utf-8", errors="replace")
    err = stderr.read().decode("utf-8", errors="replace")
    code = stdout.channel.recv_exit_status()
    return code, out, err


def build_tarball() -> bytes:
    buf = io.BytesIO()
    include = [
        "src/sally_cibote",
        "tests",
        "pyproject.toml",
        "README.md",
        "data/memory/sally_memory.db",
    ]
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for rel in include:
            path = ROOT / rel
            if not path.exists():
                print(f"SKIP missing {rel}")
                continue
            tar.add(path, arcname=rel)
        # VPS-specific env (never includes SSH secrets)
        env_text = f"""# Sally brain on VPS — generated by deploy_vps_sally.py
SALLY_OLLAMA_BASE_URL={OLLAMA_URL}
OLLAMA_HOST={OLLAMA_URL}
SALLY_OLLAMA_MODEL={MODEL}
SALLY_OLLAMA_TIMEOUT=90
SALLY_ALLOW_MOCK=0
SALLY_MEMORY_DB={REMOTE_ROOT}/data/memory/sally_memory.db
SALLY_BRAIN_HOST=0.0.0.0
SALLY_BRAIN_PORT={REMOTE_PORT}
SALLY_TTS_ENABLED=0
SALLY_LIF_ENABLED=1
SALLY_LIF_STAGE=newborn
SALLY_N8N_ENABLED=0
"""
        info = tarfile.TarInfo(name=".env")
        data = env_text.encode("utf-8")
        info.size = len(data)
        tar.addfile(info, io.BytesIO(data))
    return buf.getvalue()


def main() -> int:
    for key in ("SALLY_VPS_HOST", "SALLY_VPS_PASS"):
        if not os.environ.get(key):
            print(f"missing {key}")
            return 2

    # Safety: refuse if remote already exists with unexpected content? We create fresh.
    client = connect()
    code, out, err = run(client, f"test -e {REMOTE_ROOT} && echo EXISTS || echo NEW")
    print("path_check", out.strip(), err.strip())

    # Preflight: ensure target port free and docker ollama has qwen
    code, out, _ = run(client, f"ss -lntp | grep ':{REMOTE_PORT} ' || echo PORT_FREE")
    print("port", out.strip())
    if "PORT_FREE" not in out and f":{REMOTE_PORT}" in out:
        print("REFUSING: port busy")
        client.close()
        return 3

    code, out, _ = run(
        client,
        "curl -s http://127.0.0.1:32768/api/tags | python3 -c \"import sys,json; d=json.load(sys.stdin); print([m['name'] for m in d.get('models',[])])\"",
    )
    print("docker_ollama_models", out.strip())
    if "qwen2.5:3b" not in out:
        print("REFUSING: qwen2.5:3b not on docker ollama")
        client.close()
        return 4

    # Create directory only if missing; never rm -rf existing trees elsewhere
    run(client, f"mkdir -p {REMOTE_ROOT}")
    tgz = build_tarball()
    sftp = client.open_sftp()
    remote_tgz = "/tmp/sally-cibote-deploy.tgz"
    with sftp.file(remote_tgz, "wb") as rf:
        rf.write(tgz)
    sftp.close()
    print(f"uploaded tarball {len(tgz)} bytes")

    # Extract into /opt/sally-cibote (only our folder)
    code, out, err = run(
        client,
        f"mkdir -p {REMOTE_ROOT} && tar -xzf {remote_tgz} -C {REMOTE_ROOT} && "
        f"ls -la {REMOTE_ROOT} && ls -la {REMOTE_ROOT}/data/memory/ && "
        f"python3 -c \"import sqlite3; c=sqlite3.connect('{REMOTE_ROOT}/data/memory/sally_memory.db'); "
        f"print('memories', c.execute('select count(*) from memories').fetchone()[0])\"",
    )
    print(out)
    if err.strip():
        print("stderr", err)
    if code != 0:
        client.close()
        return 5

    # Install minimal deps in a venv inside our folder only
    code, out, err = run(
        client,
        f"cd {REMOTE_ROOT} && python3 -m venv .venv && "
        f".venv/bin/pip install -U pip && "
        f".venv/bin/pip install -e '.[dev]' httpx python-dotenv pyyaml",
        timeout=600,
    )
    print(out[-2000:] if len(out) > 2000 else out)
    if err.strip():
        print("pip_stderr_tail", err[-1500:])
    if code != 0:
        print("pip failed", code)
        client.close()
        return 6

    # systemd unit — new unit name only
    unit = f"""[Unit]
Description=Sally Cibote Brain API
After=network.target

[Service]
Type=simple
WorkingDirectory={REMOTE_ROOT}
EnvironmentFile={REMOTE_ROOT}/.env
ExecStart={REMOTE_ROOT}/.venv/bin/python -m sally_cibote.server.brain_api
Restart=on-failure
RestartSec=3

[Install]
WantedBy=multi-user.target
"""
    sftp = client.open_sftp()
    with sftp.file("/etc/systemd/system/sally-brain.service", "w") as rf:
        rf.write(unit)
    sftp.close()

    code, out, err = run(
        client,
        "systemctl daemon-reload && systemctl enable sally-brain && systemctl restart sally-brain && sleep 2 && systemctl is-active sally-brain && curl -s http://127.0.0.1:8765/health",
    )
    print("service", out)
    if err.strip():
        print("service_err", err)

    # Confirm we did not stop unrelated services
    code, out, _ = run(
        client,
        "docker ps --format '{{.Names}} {{.Status}}' | grep -E 'n8n|whatsapp|ollama-eqoj|traefik|rwp-ponto' ; "
        "systemctl is-active ollama n8n 2>/dev/null; ss -lntp | grep -E ':(5678|8080|8090|11434|32768|8765)\\b'",
    )
    print("untouched_check", out)

    client.close()
    print("DEPLOY_OK", f"http://{os.environ['SALLY_VPS_HOST']}:{REMOTE_PORT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
